#!/usr/bin/env python3
"""The desktop's logo (icons.c's logo()): user/atlas/logo-glass.svg (the
website's, the Glass look's: three frosted faces, white seams, the node
in the accent) rendered by Inkscape at 32 and 64 pixels, each reduced to
64 colours with their opacity (a palette of 0xAARRGGBB, a byte a pixel:
5 KiB), so draw.c's dl_pic can scale it smoothly and blend its edges.

  python3 tools/mklogo.py user/atlas/logo.c

Part of SIEOS. (c) Olivier Moulin. SPDX-License-Identifier: GPL-3.0-only
"""
import os, subprocess, sys, tempfile
from PIL import Image

SVG = os.path.join(os.path.dirname(__file__), "..", "user", "atlas", "logo-glass.svg")
SIZES = (32, 64)


def render(size, tmp):
    png = os.path.join(tmp, f"logo{size}.png")
    subprocess.run(["inkscape", SVG, "--export-type=png", f"--export-filename={png}", f"--export-width={size}",
                    f"--export-height={size}"], check=True, capture_output=True)
    im = Image.open(png).convert("RGBA")
    q = im.quantize(64, method=Image.Quantize.FASTOCTREE)   # (keeps the opacity: octree on RGBA)
    pal = q.getpalette(rawmode="RGBA")[:64 * 4]
    pal += [0] * (64 * 4 - len(pal))
    return list(q.getdata()), [pal[i:i + 4] for i in range(0, 64 * 4, 4)]


def main(out):
    with tempfile.TemporaryDirectory() as tmp:
        imgs = [render(s, tmp) for s in SIZES]
    with open(out, "w") as f:
        f.write("/*\n * logo.c - generated by tools/mklogo.py: the logo (logo-glass.svg) at 32\n"
                " * and 64 pixels, a byte a pixel into a palette of 64 colours 0xAARRGGBB.\n */\n"
                "#include <stdint.h>\n\n")
        f.write("const uint32_t logo_pal[2][64] = {\n")
        for _, pal in imgs:
            f.write("    { " + ", ".join(f"0x{a:02x}{r:02x}{g:02x}{b:02x}" for r, g, b, a in pal) + " },\n")
        f.write("};\n")
        for s, (px, _) in zip(SIZES, imgs):
            f.write(f"const uint8_t logo{s}[{s * s}] = {{\n")
            for y in range(s):
                f.write("    " + ",".join(str(v) for v in px[y * s:(y + 1) * s]) + ",\n")
            f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "user/atlas/logo.c")
