#!/usr/bin/env python3
"""The desktop's native font for 100% (draw.c: text at 1.5 times the 6 x 11
font, a 9 x 16 cell): printable ASCII rendered once from DejaVu Sans Mono
at 15 pixels, with FreeType's hinting, as 8-bit coverage (anti-aliased
edges), so the text is drawn pixel for pixel, never resampled. Writes
user/atlas/font15.c.

DejaVu Sans Mono: Copyright (c) 2003 Bitstream, Inc. (Bitstream Vera),
DejaVu changes are in the public domain; its license allows embedding
renderings of it in software. The rendering here is not a font file.

Usage: tools/mkfont15.py [path to DejaVuSansMono.ttf] > user/atlas/font15.c
Part of SIEOS. (c) Olivier Moulin. SPDX-License-Identifier: GPL-3.0-only
"""
import sys
from PIL import Image, ImageDraw, ImageFont

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
f = ImageFont.truetype(path, 15)
W, H, DY = 9, 16, -1                       # the cell; the glyphs a row up (the 6 x 11 font's baseline)
out = ["/*", " * font15.c - generated by tools/mkfont15.py: the native 9 x 16 font",
       " * (100%), printable ASCII, 8-bit coverage. From DejaVu Sans Mono",
       " * (Bitstream Vera license; DejaVu changes: public domain).", " */",
       "#include <stdint.h>", "", f"const uint8_t font15[95][{H}][{W}] = {{"]
for c in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, DY), chr(c), font=f, fill=255)
    px = img.load()
    rows = ["{" + ",".join(str(px[x, y]) for x in range(W)) + "}" for y in range(H)]
    out.append(f"    {{ /* {chr(c) if chr(c) not in '\\\\*/' else '?'} */ " + ",".join(rows) + " },")
out.append("};")
print("\n".join(out))
