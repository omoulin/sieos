#!/usr/bin/env python3
"""The desktop's native fonts for 100% (draw.c: text drawn pixel for
pixel, never resampled): printable ASCII rendered once from DejaVu Sans
Mono with FreeType's hinting, as 8-bit coverage (anti-aliased edges).

  font15: the body, 15 pixels in a 9 x 16 cell (1.5 times the 6 x 11 font)
  font18: titles, 18 pixels in an 11 x 20 cell (11/6 times)
  font13: small text, 13 pixels in an 8 x 15 cell (8/6 times)

DejaVu Sans Mono: Copyright (c) 2003 Bitstream, Inc. (Bitstream Vera),
DejaVu changes are in the public domain; its license allows embedding
renderings of it in software. The rendering here is not a font file.

Usage: tools/mkfont15.py [15|18|13] [path to DejaVuSansMono.ttf] > user/atlas/fontNN.c
Part of SIEOS. (c) Olivier Moulin. SPDX-License-Identifier: GPL-3.0-only
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = {15: (9, 16, -1, "the body"), 18: (11, 20, -1, "titles"), 13: (8, 15, -1, "small text")}
px_ = int(sys.argv[1]) if len(sys.argv) > 1 else 15
path = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
W, H, DY, what = SIZES[px_]                # the cell; the glyphs a row up (the 6 x 11 font's baseline)
f = ImageFont.truetype(path, px_)
out = ["/*", f" * font{px_}.c - generated by tools/mkfont15.py: the native {W} x {H} font",
       f" * (100%, {what}), printable ASCII, 8-bit coverage. From DejaVu Sans Mono",
       " * (Bitstream Vera license; DejaVu changes: public domain).", " */",
       "#include <stdint.h>", "", f"const uint8_t font{px_}[95][{H}][{W}] = {{"]
for c in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, DY), chr(c), font=f, fill=255)
    px = img.load()
    rows = ["{" + ",".join(str(px[x, y]) for x in range(W)) + "}" for y in range(H)]
    out.append(f"    {{ /* {chr(c) if chr(c) not in '\\\\*/' else '?'} */ " + ",".join(rows) + " },")
out.append("};")
print("\n".join(out))
