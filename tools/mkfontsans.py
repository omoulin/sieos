#!/usr/bin/env python3
"""The desktop's proportional fonts (draw.c's SANS text: titles, labels,
buttons; terminals and code stay in the mono fonts): printable ASCII
rendered from DejaVu Sans with FreeType's hinting, at the three native
sizes of the mono fonts (15, 18 and 13 pixels, the same cell heights and
baseline), as 4-bit coverage.

Each glyph is kept only where it has ink: its advance (pixels to the next
glyph), where its ink starts from the pen (may be left of it: 'j') and how
wide it is; its rows are packed two pixels a byte (the left one in the
high half), a row (w + 1) / 2 bytes.

DejaVu Sans: Copyright (c) 2003 Bitstream, Inc. (Bitstream Vera), DejaVu
changes are in the public domain; its license allows embedding renderings
of it in software. The rendering here is not a font file.

Usage: tools/mkfontsans.py [path to DejaVuSans.ttf] > user/atlas/fontsans.c
Part of SIEOS. (c) Olivier Moulin. SPDX-License-Identifier: GPL-3.0-only
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = [(15, 16, "the body"), (18, 20, "titles"), (13, 15, "small text")]   # (pixels, cell height): font15/18/13's
path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
PAD = 4                                    # room around the pen for overhangs while rendering

out = ["/*", " * fontsans.c - generated by tools/mkfontsans.py: the desktop's proportional",
       " * fonts at 15, 18 and 13 pixels (the mono fonts' cells: 16, 20, 15 high),",
       " * printable ASCII, 4-bit coverage. From DejaVu Sans (Bitstream Vera",
       " * license; DejaVu changes: public domain).", " */",
       '#include "fontsans.h"', ""]
fonts = []
for px_, H, what in SIZES:
    f = ImageFont.truetype(path, px_)
    glyphs, data = [], []
    for c in range(32, 127):
        adv = round(f.getlength(chr(c)))
        W = adv + 2 * PAD
        img = Image.new("L", (W, H), 0)
        ImageDraw.Draw(img).text((PAD, -1), chr(c), font=f, fill=255)
        px = img.load()
        cols = [x for x in range(W) if any(px[x, y] >= 8 for y in range(H))]
        x0, x1 = (cols[0], cols[-1] + 1) if cols else (PAD, PAD)
        w = x1 - x0
        glyphs.append((adv, w, x0 - PAD, len(data)))
        for y in range(H):
            row = [min(15, (px[x, y] + 8) // 17) for x in range(x0, x1)] + [0]
            data += [row[i] << 4 | row[i + 1] for i in range(0, w, 2)]
    out.append(f"static const uint8_t px{px_}[{len(data)}] = {{   /* {what} */")
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const sans_glyph_t g{px_}[95] = {{")
    for i in range(0, 95, 6):
        out.append("    " + " ".join(f"{{{a},{w},{x},{o}}}," for a, w, x, o in glyphs[i:i + 6]))
    out.append("};")
    fonts.append(f"    {{ {H}, g{px_}, px{px_} }},")
out.append("const sans_font_t sans_fonts[3] = {   /* 15, 18, 13: as draw.c's natives */")
out += fonts
out.append("};")
print("\n".join(out))
