/*
 * hid-test.c - host test of the HID report parser and decoder (kernel/hid.c):
 * a touchpad's mouse collection (report ID 1) beside its touchpad collection,
 * a keyboard with a key bitmap (NKRO, report ID 1), an array keyboard, an
 * absolute pointer; the keys and pointer events that come out.
 */
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <stdbool.h>
#include <stdarg.h>
#define SIEOS_POLL_H
#define kprintf printf
static uint64_t now_ns;
static uint64_t hrtime(void) { return now_ns; }
static int keys[64], nkeys, mdx, mdy, mbtn, mabs, nmouse;
static void kbd_key(uint16_t code, bool release) { keys[nkeys++] = release ? -code : code; }
static void input_mouse(int dx, int dy, unsigned b) { mdx = dx; mdy = dy; mbtn = b; mabs = 0; nmouse++; }
static void input_mouse_abs(int x, int y, unsigned b) { mdx = x; mdy = y; mbtn = b; mabs = 1; nmouse++; }
#define SIEOS_KERNEL_H
#define ARRAY_SIZE(a) (sizeof(a) / sizeof((a)[0]))
#include "../kernel/include/hid.h"
#include "../kernel/hid.c"

static int fails;
#define CHECK(c) do { if (!(c)) { printf("FAIL line %d: %s\n", __LINE__, #c); fails++; } } while (0)

static const uint8_t touchpad[] = {
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x01, 0x09, 0x01, 0xA1, 0x00,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x02, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x02, 0x81, 0x02,
    0x95, 0x06, 0x81, 0x03,
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06,
    0xC0, 0xC0,
    0x05, 0x0D, 0x09, 0x05, 0xA1, 0x01, 0x85, 0x03, 0x09, 0x22, 0xA1, 0x02,
    0x09, 0x42, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02, 0x95, 0x07, 0x81, 0x03,
    0x05, 0x01, 0x09, 0x30, 0x26, 0xFF, 0x0F, 0x75, 0x10, 0x95, 0x01, 0x81, 0x02, 0xC0, 0xC0,
};
static const uint8_t nkro[] = {
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x01, 0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00,
    0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02, 0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
    0x19, 0x00, 0x29, 0x67, 0x95, 0x68, 0x75, 0x01, 0x81, 0x02, 0xC0,
};
static const uint8_t array_kbd[] = {
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
    0x75, 0x01, 0x95, 0x08, 0x81, 0x02, 0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
    0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00, 0xC0,
};
static const uint8_t tablet[] = {             /* QEMU's usb-tablet */
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03,
    0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01,
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x00, 0x26, 0xFF, 0x7F, 0x35, 0x00, 0x46, 0xFF, 0x7F,
    0x75, 0x10, 0x95, 0x02, 0x81, 0x02, 0x05, 0x01, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x35, 0x00,
    0x45, 0x00, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06, 0xC0, 0xC0,
};

int main(void)
{
    static struct hid h;
    /* touchpad: the mouse collection is used, the touchpad one is not */
    memset(&h, 0, sizeof(h));
    CHECK(hid_parse(&h, touchpad, sizeof(touchpad)) == 0);
    CHECK(h.ids && h.has_mouse && !h.has_kbd);
    const uint8_t r1[] = { 0x01, 0x01, 0x05, 0xFD };
    hid_input(&h, r1, sizeof(r1));
    CHECK(nmouse == 1 && mdx == 5 && mdy == -3 && mbtn == 1 && !mabs);
    const uint8_t r3[] = { 0x03, 0x01, 0x34, 0x12 };
    hid_input(&h, r3, sizeof(r3));
    CHECK(nmouse == 1);                          /* (the touchpad report: ignored) */

    /* NKRO keyboard: Shift + A, then A released, then Shift released */
    memset(&h, 0, sizeof(h));
    nkeys = 0;
    CHECK(hid_parse(&h, nkro, sizeof(nkro)) == 0 && h.has_kbd && h.ids);
    uint8_t k[15] = { 0x01, 0x02, 0x00 };
    k[3 + 0x04 / 8] |= 1 << (0x04 % 8);           /* usage 4: A */
    hid_input(&h, k, sizeof(k));
    CHECK(nkeys == 2 && keys[0] == 0x2A && keys[1] == 0x1E);
    memset(k + 3, 0, sizeof(k) - 3);
    hid_input(&h, k, sizeof(k));
    k[1] = 0;
    hid_input(&h, k, sizeof(k));
    CHECK(nkeys == 4 && keys[2] == -0x1E && keys[3] == -0x2A);

    /* array keyboard: Up arrow (E0 48), repeat after 500 ms, then Ctrl+C */
    memset(&h, 0, sizeof(h));
    nkeys = 0;
    now_ns = 1000000000;
    CHECK(hid_parse(&h, array_kbd, sizeof(array_kbd)) == 0 && !h.ids);
    const uint8_t up[8] = { 0, 0, 0x52 };
    hid_input(&h, up, 8);
    CHECK(nkeys == 1 && keys[0] == 0x148);
    now_ns += 400000000;
    hid_tick(&h);
    CHECK(nkeys == 1);
    now_ns += 200000000;
    hid_tick(&h);
    CHECK(nkeys == 2 && keys[1] == 0x148);
    const uint8_t ctrlc[8] = { 0x01, 0, 0x06 };
    hid_input(&h, ctrlc, 8);
    CHECK(nkeys == 5 && keys[2] == -0x148 && keys[3] == 0x1D && keys[4] == 0x2E);
    const uint8_t roll[8] = { 0x01, 0, 1, 1, 1, 1, 1, 1 };
    hid_input(&h, roll, 8);
    CHECK(nkeys == 5);                           /* ErrorRollOver: the state stays */
    hid_release(&h);
    CHECK(nkeys == 7 && keys[5] == -0x2E && keys[6] == -0x1D);

    /* absolute pointer (0..32767): the middle, left button */
    memset(&h, 0, sizeof(h));
    CHECK(hid_parse(&h, tablet, sizeof(tablet)) == 0 && h.has_mouse);
    const uint8_t t[6] = { 0x01, 0xFF, 0x3F, 0xFF, 0x1F, 0 };
    hid_input(&h, t, sizeof(t));
    CHECK(mabs && mbtn == 1 && mdx > 32700 && mdx < 32800 && mdy > 16300 && mdy < 16400);

    printf("hid-test: %s\n", fails ? "FAILED" : "ok");
    return fails != 0;
}
